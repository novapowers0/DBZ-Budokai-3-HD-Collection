r"""defaults_historial.py - default values that changed between published versions and the current source.

  python tools\defaults_historial.py [--tags v1.5.6 v1.5.5.5 ...] [--salida res\datos\defaults_historial.toml]

Why: SaveConfig (SDK) rewrites EVERY key already present in the user's dbz3_user.toml, even when its value equals the
default. A setting that some version wrote stays pinned, and whoever updates never gets the new default.

The launcher (settings.cpp, MigrarTrasActualizar) reads this file. When the user's value is exactly the old
default of the version they come from, it moves the setting to the new default. A value the user chose (different from
that version's default) is never touched.

It reads each tag from the published repo (github/, git show) and the current source (src/).
ponytail: regex over REXCVAR_DEFINE_*; a default that is not a literal (a macro or an expression) is skipped and listed.
"""
import argparse, re, subprocess, sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]
GH = R / "github"
DEF = re.compile(r'REXCVAR_DEFINE_(BOOL|INT32|INT64|UINT32|UINT64|DOUBLE|FLOAT|STRING)\s*\(\s*(\w+)\s*,\s*'
                 r'("(?:[^"\\]|\\.)*"|[-+]?[\w.]+)\s*,')


def norma(tipo, v):
    """Literal C++ -> texto comparable (None si no es literal)."""
    if tipo == "STRING":
        return v[1:-1].encode().decode("unicode_escape") if v.startswith('"') else None
    if tipo == "BOOL":
        return v if v in ("true", "false") else None
    s = v.rstrip("fFuUlL")
    try:
        x = float(s)
    except ValueError:
        return None
    return str(int(x)) if x == int(x) and tipo not in ("DOUBLE", "FLOAT") else repr(x)


def extraer(textos):
    d, raros = {}, []
    for t in textos:
        for m in DEF.finditer(t):
            v = norma(m.group(1), m.group(3))
            if v is None:
                raros.append(m.group(2))
            else:
                d[m.group(2)] = (m.group(1), v)
    return d, raros


def textos_tag(tag):
    nombres = subprocess.run(["git", "-C", str(GH), "ls-tree", "-r", "--name-only", tag, "src"],
                             capture_output=True, text=True, check=True).stdout.split()
    for n in nombres:
        if n.endswith((".cpp", ".h", ".inl")):
            yield subprocess.run(["git", "-C", str(GH), "show", f"{tag}:{n}"], capture_output=True,
                                 text=True, encoding="utf-8", errors="replace").stdout


def textos_actual():
    for p in (R / "src").rglob("*"):
        if p.suffix in (".cpp", ".h", ".inl"):
            yield p.read_text(encoding="utf-8", errors="replace")


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tags", nargs="*", default=["v1.5.6", "v1.5.5.5"])
    ap.add_argument("--salida", default=str(R / "res" / "datos" / "defaults_historial.toml"))
    a = ap.parse_args()
    actual, _ = extraer(textos_actual())
    out = ["# Generated by tools/defaults_historial.py: per published version, the cvars whose default differs from",
           "# the current build. Read by settings.cpp (MigrarTrasActualizar). Don't edit by hand.", ""]
    for tag in a.tags:
        viejo, raros = extraer(textos_tag(tag))
        cambios = {k: v[1] for k, v in viejo.items() if k in actual and actual[k][1] != v[1]}
        out.append(f'["{tag.lstrip("v")}"]')
        out += [f"{k} = {toml_str(v)}" for k, v in sorted(cambios.items())]
        out.append("")
        print(f"{tag}: {len(viejo)} cvars, {len(cambios)} con otro valor de serie hoy; {len(set(raros))} no literales",
              file=sys.stderr)
        for k, v in sorted(cambios.items()):
            print(f"  {k}: {v} -> {actual[k][1]}", file=sys.stderr)
    Path(a.salida).write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    assert norma("BOOL", "true") == "true" and norma("INT32", "3") == "3" and norma("DOUBLE", "0.5f") == "0.5"
    assert norma("STRING", '"a\\\\b"') == "a\\b" and norma("INT32", "kFoo") is None
    main()
